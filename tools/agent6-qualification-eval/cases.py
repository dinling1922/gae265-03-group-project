"""合格判定埋錯集的樣本內容與正確答案（全部是虛構資料）。

每一份樣本只針對一條「incomplete（缺了就不合格）」規則埋錯，同一份文件的其他必要欄位都寫齊，
這樣結果只反映被測的那一條規則。

正確答案依照文件的**實際內容**和規則的用意（qualification_rules.json 的 source／missing_reason、
docs/agents/handoff/agent-6-document.md）判斷，不是依照目前規則會怎麼判：
- 合格（pass）：文件上真的寫了這個欄位，人工審核會收。
- 不合格（fail）：文件上沒有這個欄位（缺欄位），或只有看起來像、其實不是這個欄位的字（陷阱）。

版本（version）：
- complete：完整版，應該合格
- missing：缺欄位版，應該不合格
- trap：陷阱版，應該不合格，但容易被目前的規則誤放
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Case:
    name: str
    code: str  # 文件代碼
    field: str  # 被測的規則欄位（qualification_rules.json 的 field）
    label: str  # 規則的欄位名稱（不合格時 missing 應該是它）
    version: str  # complete / missing / trap
    expected: str  # pass / fail
    lang: str  # zh / en / ja（選字型用）
    lines: tuple[str, ...]
    why: str  # 為什麼答案是這樣


